package crucible.oracle;

import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Collectors;

import forge.game.player.PlayerController;

/**
 * Writes RecordingControllerBase.java: one override per abstract
 * PlayerController method, each delegating to PlayerControllerAi and reporting
 * the call to the recorder's hooks (ADR-0059). Generated by reflection so an
 * upstream method added to PlayerController shows up as a diff here, and
 * GameRecorder exits 4 until it is regenerated.
 *
 * Usage: RecorderGen <output .java file>.
 */
public final class RecorderGen {
    private RecorderGen() {
    }

    public static void main(String[] args) throws Exception {
        List<Method> methods = abstractMethods();
        StringBuilder b = new StringBuilder();
        b.append("// Code generated by RecorderGen; DO NOT EDIT.\n\n");
        b.append("package crucible.oracle;\n\n");
        b.append("import forge.LobbyPlayer;\n");
        b.append("import forge.ai.PlayerControllerAi;\n");
        b.append("import forge.game.Game;\n");
        b.append("import forge.game.player.Player;\n\n");
        b.append("/**\n");
        b.append(" * Every abstract PlayerController method, answered by PlayerControllerAi and\n");
        b.append(" * reported to {@link #before} and {@link #after} (ADR-0059). A void method\n");
        b.append(" * reports a null answer.\n");
        b.append(" */\n");
        b.append("@SuppressWarnings({\"unchecked\", \"rawtypes\", \"deprecation\"})\n");
        b.append("abstract class RecordingControllerBase extends PlayerControllerAi {\n");
        b.append("    RecordingControllerBase(Game game, Player p, LobbyPlayer lp) {\n");
        b.append("        super(game, p, lp);\n");
        b.append("    }\n\n");
        b.append("    /** Called before the AI answers; the arguments are the options offered. */\n");
        b.append("    abstract void before(String method, Object[] args);\n\n");
        b.append("    /** Called after the AI answered, with the answer (null for void). */\n");
        b.append("    abstract <R> R after(String method, Object[] args, R answer);\n");
        for (Method m : methods) {
            b.append('\n').append(override(m));
        }
        b.append("}\n");
        Files.writeString(Path.of(args[0]), b.toString());
    }

    /** The public abstract methods of PlayerController, in a stable order. */
    static List<Method> abstractMethods() {
        List<Method> out = new ArrayList<>();
        for (Method m : PlayerController.class.getDeclaredMethods()) {
            if (Modifier.isAbstract(m.getModifiers()) && Modifier.isPublic(m.getModifiers())) {
                out.add(m);
            }
        }
        out.sort(Comparator.comparing(RecorderGen::key));
        return out;
    }

    static String key(Method m) {
        return m.getName() + Arrays.stream(m.getParameterTypes()).map(Class::getName)
                .collect(Collectors.joining(",", "(", ")"));
    }

    private static String override(Method m) {
        StringBuilder b = new StringBuilder("    @Override\n    public ");
        TypeVariable<Method>[] tvs = m.getTypeParameters();
        if (tvs.length > 0) {
            b.append(Arrays.stream(tvs).map(RecorderGen::typeParam).collect(Collectors.joining(", ", "<", "> ")));
        }
        boolean isVoid = m.getReturnType() == void.class;
        b.append(isVoid ? "void" : render(aiReturnType(m))).append(' ').append(m.getName()).append('(');
        Type[] ps = m.getGenericParameterTypes();
        List<String> names = new ArrayList<>();
        for (int i = 0; i < ps.length; i++) {
            String t = render(ps[i]);
            if (m.isVarArgs() && i == ps.length - 1) {
                t = t.substring(0, t.length() - 2) + "...";
            }
            names.add("a" + i);
            b.append(i > 0 ? ", " : "").append("final ").append(t).append(" a").append(i);
        }
        String argv = "new Object[] {" + String.join(", ", names) + "}";
        String call = "super." + m.getName() + "(" + String.join(", ", names) + ")";
        b.append(") {\n");
        b.append("        Object[] args = ").append(argv).append(";\n");
        b.append("        before(\"").append(m.getName()).append("\", args);\n");
        if (isVoid) {
            b.append("        ").append(call).append(";\n");
            b.append("        after(\"").append(m.getName()).append("\", args, null);\n");
        } else {
            b.append("        return after(\"").append(m.getName()).append("\", args, ").append(call).append(");\n");
        }
        b.append("    }\n");
        return b.toString();
    }

    // PlayerControllerAi may narrow a return type (CardCollection for
    // CardCollectionView); the override must match the narrower one.
    private static Type aiReturnType(Method m) {
        try {
            return forge.ai.PlayerControllerAi.class.getMethod(m.getName(), m.getParameterTypes())
                    .getGenericReturnType();
        } catch (NoSuchMethodException e) {
            return m.getGenericReturnType();
        }
    }

    private static String typeParam(TypeVariable<?> tv) {
        Type[] bounds = tv.getBounds();
        if (bounds.length == 1 && bounds[0] == Object.class) {
            return tv.getName();
        }
        return tv.getName() + " extends "
                + Arrays.stream(bounds).map(RecorderGen::render).collect(Collectors.joining(" & "));
    }

    // Source spelling of a reflected type: nested classes with '.', not '$'.
    static String render(Type t) {
        if (t instanceof Class<?> c) {
            if (c.isArray()) {
                return render(c.getComponentType()) + "[]";
            }
            return c.getName().replace('$', '.');
        }
        if (t instanceof ParameterizedType p) {
            return render(p.getRawType()) + Arrays.stream(p.getActualTypeArguments()).map(RecorderGen::render)
                    .collect(Collectors.joining(", ", "<", ">"));
        }
        if (t instanceof WildcardType w) {
            if (w.getLowerBounds().length > 0) {
                return "? super " + render(w.getLowerBounds()[0]);
            }
            Type[] up = w.getUpperBounds();
            return up.length == 0 || up[0] == Object.class ? "?" : "? extends " + render(up[0]);
        }
        if (t instanceof GenericArrayType g) {
            return render(g.getGenericComponentType()) + "[]";
        }
        if (t instanceof TypeVariable<?> v) {
            return v.getName();
        }
        throw new IllegalArgumentException("type " + t);
    }
}
